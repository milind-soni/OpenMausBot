import { expect, it } from "vitest";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { launchVerificationServer } from "../../scripts/control-omb.ts";
import { startFakeConnectedApps } from "../testing/fake-connected-apps.ts";

it("prepares, tests, approves and runs an automation through the isolated app", async () => {
  const apps = await startFakeConnectedApps();
  apps.workflowSchemas = true;
  const scratch = mkdtempSync(join(tmpdir(), "omb-minimum-ai-host-"));
  const modelLog = join(scratch, "model.log");
  apps.emails.push({ messageId: "m1", threadId: "t1", messageTimestamp: new Date().toISOString(), subject: "Sample", sender: "test@example.test" });
  const plan = { version: 1, steps: [{ kind: "call", id: "inbox", tool: "GMAIL_FETCH_EMAILS", input: { user_id: "me", query: "after:0" } }], output: { $ref: "inbox.messages" } };
  const fixture = await launchVerificationServer({ ...process.env, OMB_MINIMUM_AI_EXPERIMENT: "1", OMB_COMPOSIO_BROKER_URL: apps.url, OMB_COMPOSIO_BROKER_TOKEN: apps.token, FAKE_CLAUDE_TEXT_LOG: modelLog, FAKE_CLAUDE_TEXT_RESULT: JSON.stringify({ type: "result", is_error: false, result: JSON.stringify(plan) }) });
  const api = async (method: string, path: string, body?: unknown) => {
    const response = await fetch(fixture.info.url + path, { method, headers: { "content-type": "application/json", origin: fixture.info.url }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    const result = await response.json() as any;
    if (!response.ok) throw new Error(`${response.status}: ${JSON.stringify(result)}`);
    return result;
  };
  try {
    expect((await api("GET", "/api/config")).features.minimumAi).toBe(true);
    const bot = (await api("POST", "/api/bots", { name: "Workflow fixture" })).bot;
    await api("PATCH", `/api/bots/${bot.id}`, { composio: true, connectorScopes: { apps: { gmail: "read" } } });
    const routine = (await api("POST", "/api/routines", { name: "Read inbox", prompt: "Read my inbox", botId: bot.id, target: "bot", runOn: "maus", schedule: { type: "once", at: Date.now() + 60_000 }, executionMode: "minimum-ai", enabled: false })).routine;
    await expect(api("PATCH", `/api/routines/${routine.id}`, { enabled: true })).rejects.toThrow(/review and approve/i);
    const base = `/api/routines/${routine.id}/minimum-ai`;
    const draft = (await api("POST", `${base}/prepare`, {})).workflow;
    expect(draft.approved).toBe(false);
    expect((await api("POST", `${base}/test`, { fingerprint: draft.fingerprint })).result).toMatchObject({ status: "completed", output: [{ subject: "Sample" }] });
    expect(apps.calls.find((call) => call.tool === "GMAIL_FETCH_EMAILS")?.item.account).toBe("fake-gmail-account");
    expect((await api("POST", `${base}/approve`, { fingerprint: draft.fingerprint })).workflow.approved).toBe(true);
    const searchesBefore = apps.calls.filter((call) => call.tool === "COMPOSIO_SEARCH_TOOLS").length;
    const modelCallsBefore = readFileSync(modelLog, "utf8").trim().split("\n").length;
    const run = (await api("POST", `/api/routines/${routine.id}/run`, {})).run;
    await expect.poll(async () => (await api("GET", "/api/routines")).runs.find((entry: { id: string }) => entry.id === run.id)?.status, { timeout: 20_000 }).toBe("completed");
    const finished = (await api("GET", "/api/routines")).runs.find((entry: { id: string }) => entry.id === run.id);
    expect(finished.output).toContain("Sample");
    const reports = (await api("GET", `/api/threads/${finished.resultsThreadId ?? bot.threadId}/messages?limit=100`)).messages;
    expect(reports.some((message: { kind: string; routineRun?: { runId: string; summary?: string } }) => message.kind === "routine.run" && message.routineRun?.runId === run.id && message.routineRun?.summary?.includes("Sample"))).toBe(true);
    expect(apps.calls.filter((call) => call.tool === "COMPOSIO_SEARCH_TOOLS")).toHaveLength(searchesBefore);
    expect(apps.calls.filter((call) => call.tool === "GMAIL_FETCH_EMAILS")).toHaveLength(2);
    await api("PATCH", `/api/routines/${routine.id}`, { enabled: true, schedule: { type: "once", at: Date.now() + 3_000 } });
    await expect.poll(async () => (await api("GET", "/api/routines")).runs.filter((entry: { routineId: string; status: string }) => entry.routineId === routine.id && entry.status === "completed").length, { timeout: 15_000 }).toBe(2);
    expect(apps.calls.filter((call) => call.tool === "GMAIL_FETCH_EMAILS")).toHaveLength(3);
    expect(apps.calls.filter((call) => call.tool === "COMPOSIO_SEARCH_TOOLS")).toHaveLength(searchesBefore);
    expect(readFileSync(modelLog, "utf8").trim().split("\n")).toHaveLength(modelCallsBefore);
    apps.workflowDelayMs = 1_000;
    const cancelled = (await api("POST", `/api/routines/${routine.id}/run`, {})).run;
    await expect.poll(() => apps.calls.filter((call) => call.tool === "GMAIL_FETCH_EMAILS").length, { timeout: 10_000 }).toBe(4);
    await api("POST", `/api/routine-runs/${cancelled.id}/cancel`, {});
    await expect.poll(async () => (await api("GET", "/api/routines")).runs.find((entry: { id: string }) => entry.id === cancelled.id)?.status, { timeout: 10_000 }).toBe("cancelled");
    await expect.poll(async () => { try { await api("GET", base); return true; } catch { return false; } }, { timeout: 10_000 }).toBe(true);
    expect((await api("GET", base)).interrupted).toBe(true);
    await api("POST", `${base}/acknowledge`, { confirm: true });
    apps.workflowDelayMs = 0;
    apps.gmailError = "The mailbox is temporarily unavailable";
    const failed = (await api("POST", `/api/routines/${routine.id}/run`, {})).run;
    await expect.poll(async () => (await api("GET", "/api/routines")).runs.find((entry: { id: string }) => entry.id === failed.id), { timeout: 10_000 }).toMatchObject({ status: "failed", partial: true });
    expect(apps.calls.filter((call) => call.tool === "GMAIL_FETCH_EMAILS")).toHaveLength(5);
    expect((await api("GET", base)).interrupted).toBe(true);
    apps.connected.gmail = false;
    expect((await api("GET", `${base}/recovery`)).interrupted).toBe(true);
    expect(await api("POST", `${base}/acknowledge`, { confirm: true })).toMatchObject({ workflow: null, interrupted: false });
    const revoked = (await api("POST", `/api/routines/${routine.id}/run`, {})).run;
    await expect.poll(async () => (await api("GET", "/api/routines")).runs.find((entry: { id: string }) => entry.id === revoked.id)?.status, { timeout: 10_000 }).toBe("failed");
    expect(apps.calls.filter((call) => call.tool === "GMAIL_FETCH_EMAILS")).toHaveLength(5);
    expect(readFileSync(modelLog, "utf8").trim().split("\n")).toHaveLength(modelCallsBefore);
  } finally { await fixture.close(); await apps.close(); rmSync(scratch, { recursive: true, force: true }); }
}, 120_000);
