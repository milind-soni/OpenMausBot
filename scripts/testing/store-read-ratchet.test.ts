function sourceFiles(): string[] {
  const out = execFileSync("git", ["ls-files", "src"], { cwd: ROOT, encoding: "utf8" });
  return out.split("\n").filter((file) => /\.(ts|tsx)$/.test(file) && !file.includes(".test.") && !file.includes("/testing/"));
}

describe("whole-store reads", () => {
  it("no file calls useStore() more often than written here", () => {
    const grown: string[] = [], shrunk: string[] = [];
    for (const file of sourceFiles()) {
      const calls = storeReadsIn(readFileSync(new URL(file, ROOT), "utf8"));
      const written = READS[file] ?? 0;
      if (calls > written) grown.push(`${file} calls useStore() ${calls} times, ${written ? `more than ${written}` : "and is not listed"}: select what it draws with useStoreSelector`);
      else if (calls < written) shrunk.push(`${file}: ${written} → ${calls}`);
    }
    if (shrunk.length) console.info(`Fewer useStore() calls than written in scripts/testing/store-read-ratchet.test.ts; lower these numbers (or run node scripts/tighten-ratchets.mjs):\n${shrunk.join("\n")}`);
    expect(grown, "See src/state/store-select.ts").toEqual([]);
  });
});
